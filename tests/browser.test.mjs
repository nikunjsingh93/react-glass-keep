import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { once } from 'node:events';

test('editor saves, immediate ownership, safe Markdown, conflicts and cache cleanup in browser',async t=>{
  const dir=await mkdtemp(path.join(tmpdir(),'glass-browser-'));
  const base='http://127.0.0.1:18089';
  const child=spawn(process.execPath,['server/index.js'],{env:{...process.env,NODE_ENV:'production',API_PORT:'18089',DB_FILE:path.join(dir,'notes.db'),JWT_SECRET:'browser-test-only-random-long-secret-123456789',INITIAL_ADMIN_USERNAME:'operator',INITIAL_ADMIN_PASSWORD:'browser-test-password-123'},stdio:'pipe'});
  let logs=''; child.stderr.on('data',b=>logs+=b);
  t.after(async()=>{if(child.exitCode===null){child.kill();await once(child,'exit');}await rm(dir,{recursive:true,force:true});});
  for(let i=0;i<100;i++){try{if((await fetch(base+'/api/health')).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));if(i===99)throw new Error(logs);}
  const browser=await chromium.launch({channel:'msedge',headless:true}); t.after(()=>browser.close());
  const context=await browser.newContext(); const page=await context.newPage();
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base); await page.getByPlaceholder('Username',{exact:true}).fill('operator'); await page.getByPlaceholder('Password',{exact:true}).fill('browser-test-password-123'); await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await page.locator('input[placeholder="Write a note..."]').click();
  await page.getByPlaceholder('Title',{exact:true}).fill('Browser-created note');
  await page.locator('textarea').fill('Initial content');
  await page.getByRole('button',{name:'Add Note',exact:true}).click();
  await page.locator('.note-card').filter({hasText:'Browser-created note'}).click();
  await page.getByRole('button',{name:'Collaborate',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Add Collaborator',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Edit mode',exact:true}).click();
  await page.locator('textarea').fill('Saved from browser');
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.locator('.note-card').filter({hasText:'Saved from browser'})).toBeVisible();
  const session=await page.evaluate(()=>JSON.parse(localStorage.getItem('glass-keep-auth')));
  const api=async(route,method='GET',body)=>{const response=await fetch(base+'/api'+route,{method,headers:{Authorization:`Bearer ${session.token}`,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});return response.json();};
  const note=(await api('/notes'))[0];
  // A delayed acknowledgment must not replace data fetched from a later write.
  await page.locator('.note-card').filter({hasText:'Browser-created note'}).click();
  await page.getByRole('button',{name:'Edit mode',exact:true}).click();
  await page.locator('textarea').fill('Local delayed save');
  await page.route(`**/api/notes/${note.id}`,async route=>{
    const response=await route.fetch();
    const saved=await response.json();
    await api(`/notes/${note.id}`,'PATCH',{revision:saved.revision,content:'Remote after delayed save'});
    await expect(page.locator('.note-card').filter({hasText:'Remote after delayed save'})).toHaveCount(1);
    await route.fulfill({response});
  },{times:1});
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await expect(page.locator('.note-card').filter({hasText:'Remote after delayed save'})).toBeVisible();
  await api('/admin/users','POST',{name:'Editor',email:'editor',password:'browser-editor-password-123'});
  await api(`/notes/${note.id}/collaborate`,'POST',{username:'editor'});
  await page.reload();
  await page.locator('.note-card').filter({hasText:'Browser-created note'}).click();
  await page.getByRole('button',{name:'Edit mode',exact:true}).click();
  await page.locator('textarea').fill('My draft must survive');
  const current=(await api('/notes'))[0];
  await api(`/notes/${note.id}`,'PATCH',{revision:current.revision,content:'Remote collaborator edit'});
  await expect(page.getByRole('alert')).toContainText('changed on another device');
  await expect(page.locator('textarea')).toHaveValue('My draft must survive');
  await expect(page.getByRole('button',{name:'Download my draft'})).toBeVisible();
  page.on('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Reload latest notes'}).click();
  await expect(page.locator('.note-card').filter({hasText:'Remote collaborator edit'})).toBeVisible();
  await api('/notes','POST',{title:'Unsafe Markdown',content:'<img src=x onerror="window.__xss=1"><a href="javascript:window.__xss=2">bad</a>\n**Safe bold**'});
  await page.reload(); await page.locator('.note-card').filter({hasText:'Unsafe Markdown'}).click();
  await expect(page.locator('.note-content strong')).toHaveText('Safe bold');
  assert.equal(await page.evaluate(()=>window.__xss),undefined);
  assert.equal(await page.locator('.note-content [onerror],.note-content a[href^="javascript:"]').count(),0);
  await page.evaluate(async()=>{const cache=await caches.open('notes-cache');await cache.put('/api/notes',new Response('[{"title":"old private data"}]'));});
  await page.reload();
  assert.equal(await page.evaluate(()=>caches.has('notes-cache')),false);
  await page.getByRole('button',{name:'Menu',exact:true}).click();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await page.getByPlaceholder('Username',{exact:true}).fill('editor');
  await page.getByPlaceholder('Password',{exact:true}).fill('browser-editor-password-123');
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page.locator('.note-card').filter({hasText:'Remote collaborator edit'})).toBeVisible();
  await expect(page.locator('.note-card').filter({hasText:'Unsafe Markdown'})).toHaveCount(0);
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await context.setOffline(true);
  await page.reload();
  await expect(page.locator('.note-card').filter({hasText:'Remote collaborator edit'})).toBeVisible();
  await expect(page.locator('.note-card').filter({hasText:'Unsafe Markdown'})).toHaveCount(0);
  assert.deepEqual(errors,[]);
});
